            alt_trans <= 16'd0;
            d2_bit_prev <= 1'b0;
            d2_bit_seen <= 1'b0;
            bit_no <= 8'd0;
            period_cnt <= 16'd0;
            period_sum <= 16'd0;
        end else begin
            if (!dsd_active) begin
                // Idle: reset the acquisition for the next DSD session.
                decide_done <= 1'b0;
                use_alt <= 1'b0;
                acq_cnt <= 32'd0;
                alt_trans <= 16'd0;
                d2_bit_prev <= d2_sync[1];
                d2_bit_seen <= 1'b0;
                bit_no <= 8'd0;
                period_cnt <= 16'd0;
                period_sum <= 16'd0;
            end else begin
                if (acq_cnt != ACQ_CYCLES)
                    acq_cnt <= acq_cnt + 32'd1;

                if (!decide_done && (acq_cnt == ACQ_CYCLES)) begin
                    decide_done <= 1'b1;
                    use_alt <= (alt_trans >= ALT_THRESH);
                    // Averaged bit period -> decimation factor.
                    if (period_sum <= 32'd768)
                        decim_sel <= 2'd3;      // 2 MCLK  -> DSD512 (/64)
                    else if (period_sum <= 32'd1536)
                        decim_sel <= 2'd2;      // 4 MCLK  -> DSD256 (/32)
                    else if (period_sum <= 32'd3072)
                        decim_sel <= 2'd1;      // 8 MCLK  -> DSD128 (/16)
                    else
                        decim_sel <= 2'd0;      // 16 MCLK -> DSD64  (/8)
                end

                // DATA2 transition count (only while deciding). Sample only
                // at DSD bit boundaries so activity between bits is ignored.
                if (bit_en) begin
                    if (!d2_bit_seen) begin
                        d2_bit_prev <= d2_sync[1];
                        d2_bit_seen <= 1'b1;
                    end else begin
                        if (d2_sync[1] != d2_bit_prev) begin
                            d2_bit_prev <= d2_sync[1];
                            if (!decide_done && (alt_trans != 16'hffff))
                                alt_trans <= alt_trans + 16'd1;
                        end
                    end
                end

                // Bit period accumulation over the first 256 bits.
                if (bit_en) begin
                    if (bit_no != 8'hff)
                        bit_no <= bit_no + 8'd1;
                    if ((bit_no < 8'd255) && (period_sum < 16'hffff))
                        period_sum <= period_sum + period_cnt;
                    period_cnt <= 16'd1;
                end else if (period_cnt != 16'hffff) begin
                    period_cnt <= period_cnt + 16'd1;
                end
            end
        end
    end

    // ---------------- 1-bit delay lines (1024 stages each) ----------------
    reg [TAPS-1:0] sr_l;
    reg [TAPS-1:0] sr_r;
    // The accumulator spans 128 MCLK cycles. Keep its input window fixed for
    // that interval; otherwise the live shift register advances while the
    // tap sweep is in progress and the result is not a convolution.
    reg [TAPS-1:0] fir_sr_l;
    reg [TAPS-1:0] fir_sr_r;

    always @(posedge mclk or negedge rst_n) begin
        if (!rst_n) begin
            sr_l <= {TAPS{1'b0}};
            sr_r <= {TAPS{1'b0}};
        end else if (bit_en && dsd_active) begin
            sr_l <= {sr_l[TAPS-2:0], d1_sync[1]};
            sr_r <= {sr_r[TAPS-2:0], use_alt ? d2_sync[1] : lr_sync[1]};
        end
    end

    // ---------------- coefficient storage: 8 SDPB blocks ----------------
    // Block j holds coeff[j + 8i], i = 0..127 (one read port each); the
    // tap group 8k..8k+7 is read from the word k of every block.
    reg [6:0]  tapk;
    reg [9:0]  tap_base;    // (previous tapk) * 8: aligns the 1-cycle RAM latency
    wire [13:0] ram_b = {2'd0, tapk, 5'd0};      // read word = tapk

    wire [31:0] csel0, csel1, csel2, csel3, csel4, csel5, csel6, csel7;

    SDPB #(
        .INIT_RAM_00(DSD_B0_00), .INIT_RAM_01(DSD_B0_01), .INIT_RAM_02(DSD_B0_02),
        .INIT_RAM_03(DSD_B0_03), .INIT_RAM_04(DSD_B0_04), .INIT_RAM_05(DSD_B0_05),
        .INIT_RAM_06(DSD_B0_06), .INIT_RAM_07(DSD_B0_07), .INIT_RAM_08(DSD_B0_08),
        .INIT_RAM_09(DSD_B0_09), .INIT_RAM_0A(DSD_B0_0A), .INIT_RAM_0B(DSD_B0_0B),
        .INIT_RAM_0C(DSD_B0_0C), .INIT_RAM_0D(DSD_B0_0D), .INIT_RAM_0E(DSD_B0_0E),
        .INIT_RAM_0F(DSD_B0_0F)
    ) cb0 (
        .DO(csel0), .DI(32'd0), .BLKSELA(3'd0), .BLKSELB(3'd0),
        .ADA(14'd0), .ADB(ram_b),
        .CLKA(mclk), .CLKB(mclk), .CEA(1'b0), .CEB(1'b1),
        .OCE(1'b1), .RESET(1'b0)
    );

    SDPB #(
        .INIT_RAM_00(DSD_B1_00), .INIT_RAM_01(DSD_B1_01), .INIT_RAM_02(DSD_B1_02),
        .INIT_RAM_03(DSD_B1_03), .INIT_RAM_04(DSD_B1_04), .INIT_RAM_05(DSD_B1_05),
        .INIT_RAM_06(DSD_B1_06), .INIT_RAM_07(DSD_B1_07), .INIT_RAM_08(DSD_B1_08),
        .INIT_RAM_09(DSD_B1_09), .INIT_RAM_0A(DSD_B1_0A), .INIT_RAM_0B(DSD_B1_0B),
        .INIT_RAM_0C(DSD_B1_0C), .INIT_RAM_0D(DSD_B1_0D), .INIT_RAM_0E(DSD_B1_0E),
        .INIT_RAM_0F(DSD_B1_0F)
    ) cb1 (
        .DO(csel1), .DI(32'd0), .BLKSELA(3'd0), .BLKSELB(3'd0),
        .ADA(14'd0), .ADB(ram_b),
        .CLKA(mclk), .CLKB(mclk), .CEA(1'b0), .CEB(1'b1),
        .OCE(1'b1), .RESET(1'b0)
    );

    SDPB #(
        .INIT_RAM_00(DSD_B2_00), .INIT_RAM_01(DSD_B2_01), .INIT_RAM_02(DSD_B2_02),
        .INIT_RAM_03(DSD_B2_03), .INIT_RAM_04(DSD_B2_04), .INIT_RAM_05(DSD_B2_05),
        .INIT_RAM_06(DSD_B2_06), .INIT_RAM_07(DSD_B2_07), .INIT_RAM_08(DSD_B2_08),
        .INIT_RAM_09(DSD_B2_09), .INIT_RAM_0A(DSD_B2_0A), .INIT_RAM_0B(DSD_B2_0B),
        .INIT_RAM_0C(DSD_B2_0C), .INIT_RAM_0D(DSD_B2_0D), .INIT_RAM_0E(DSD_B2_0E),
        .INIT_RAM_0F(DSD_B2_0F)
    ) cb2 (
        .DO(csel2), .DI(32'd0), .BLKSELA(3'd0), .BLKSELB(3'd0),
        .ADA(14'd0), .ADB(ram_b),
        .CLKA(mclk), .CLKB(mclk), .CEA(1'b0), .CEB(1'b1),
        .OCE(1'b1), .RESET(1'b0)
    );

    SDPB #(
        .INIT_RAM_00(DSD_B3_00), .INIT_RAM_01(DSD_B3_01), .INIT_RAM_02(DSD_B3_02),
        .INIT_RAM_03(DSD_B3_03), .INIT_RAM_04(DSD_B3_04), .INIT_RAM_05(DSD_B3_05),
        .INIT_RAM_06(DSD_B3_06), .INIT_RAM_07(DSD_B3_07), .INIT_RAM_08(DSD_B3_08),
        .INIT_RAM_09(DSD_B3_09), .INIT_RAM_0A(DSD_B3_0A), .INIT_RAM_0B(DSD_B3_0B),
        .INIT_RAM_0C(DSD_B3_0C), .INIT_RAM_0D(DSD_B3_0D), .INIT_RAM_0E(DSD_B3_0E),
        .INIT_RAM_0F(DSD_B3_0F)
    ) cb3 (
        .DO(csel3), .DI(32'd0), .BLKSELA(3'd0), .BLKSELB(3'd0),
        .ADA(14'd0), .ADB(ram_b),
        .CLKA(mclk), .CLKB(mclk), .CEA(1'b0), .CEB(1'b1),
        .OCE(1'b1), .RESET(1'b0)
    );

    SDPB #(
        .INIT_RAM_00(DSD_B4_00), .INIT_RAM_01(DSD_B4_01), .INIT_RAM_02(DSD_B4_02),
        .INIT_RAM_03(DSD_B4_03), .INIT_RAM_04(DSD_B4_04), .INIT_RAM_05(DSD_B4_05),
        .INIT_RAM_06(DSD_B4_06), .INIT_RAM_07(DSD_B4_07), .INIT_RAM_08(DSD_B4_08),
        .INIT_RAM_09(DSD_B4_09), .INIT_RAM_0A(DSD_B4_0A), .INIT_RAM_0B(DSD_B4_0B),
        .INIT_RAM_0C(DSD_B4_0C), .INIT_RAM_0D(DSD_B4_0D), .INIT_RAM_0E(DSD_B4_0E),
        .INIT_RAM_0F(DSD_B4_0F)
    ) cb4 (
        .DO(csel4), .DI(32'd0), .BLKSELA(3'd0), .BLKSELB(3'd0),
        .ADA(14'd0), .ADB(ram_b),
        .CLKA(mclk), .CLKB(mclk), .CEA(1'b0), .CEB(1'b1),
        .OCE(1'b1), .RESET(1'b0)
    );

    SDPB #(
        .INIT_RAM_00(DSD_B5_00), .INIT_RAM_01(DSD_B5_01), .INIT_RAM_02(DSD_B5_02),
        .INIT_RAM_03(DSD_B5_03), .INIT_RAM_04(DSD_B5_04), .INIT_RAM_05(DSD_B5_05),
        .INIT_RAM_06(DSD_B5_06), .INIT_RAM_07(DSD_B5_07), .INIT_RAM_08(DSD_B5_08),
        .INIT_RAM_09(DSD_B5_09), .INIT_RAM_0A(DSD_B5_0A), .INIT_RAM_0B(DSD_B5_0B),
        .INIT_RAM_0C(DSD_B5_0C), .INIT_RAM_0D(DSD_B5_0D), .INIT_RAM_0E(DSD_B5_0E),
        .INIT_RAM_0F(DSD_B5_0F)
    ) cb5 (
        .DO(csel5), .DI(32'd0), .BLKSELA(3'd0), .BLKSELB(3'd0),
        .ADA(14'd0), .ADB(ram_b),
        .CLKA(mclk), .CLKB(mclk), .CEA(1'b0), .CEB(1'b1),
        .OCE(1'b1), .RESET(1'b0)
    );

    SDPB #(
        .INIT_RAM_00(DSD_B6_00), .INIT_RAM_01(DSD_B6_01), .INIT_RAM_02(DSD_B6_02),
        .INIT_RAM_03(DSD_B6_03), .INIT_RAM_04(DSD_B6_04), .INIT_RAM_05(DSD_B6_05),
        .INIT_RAM_06(DSD_B6_06), .INIT_RAM_07(DSD_B6_07), .INIT_RAM_08(DSD_B6_08),
        .INIT_RAM_09(DSD_B6_09), .INIT_RAM_0A(DSD_B6_0A), .INIT_RAM_0B(DSD_B6_0B),
        .INIT_RAM_0C(DSD_B6_0C), .INIT_RAM_0D(DSD_B6_0D), .INIT_RAM_0E(DSD_B6_0E),
        .INIT_RAM_0F(DSD_B6_0F)
    ) cb6 (
        .DO(csel6), .DI(32'd0), .BLKSELA(3'd0), .BLKSELB(3'd0),
        .ADA(14'd0), .ADB(ram_b),
        .CLKA(mclk), .CLKB(mclk), .CEA(1'b0), .CEB(1'b1),
        .OCE(1'b1), .RESET(1'b0)
    );

    SDPB #(
        .INIT_RAM_00(DSD_B7_00), .INIT_RAM_01(DSD_B7_01), .INIT_RAM_02(DSD_B7_02),
        .INIT_RAM_03(DSD_B7_03), .INIT_RAM_04(DSD_B7_04), .INIT_RAM_05(DSD_B7_05),
        .INIT_RAM_06(DSD_B7_06), .INIT_RAM_07(DSD_B7_07), .INIT_RAM_08(DSD_B7_08),
        .INIT_RAM_09(DSD_B7_09), .INIT_RAM_0A(DSD_B7_0A), .INIT_RAM_0B(DSD_B7_0B),
        .INIT_RAM_0C(DSD_B7_0C), .INIT_RAM_0D(DSD_B7_0D), .INIT_RAM_0E(DSD_B7_0E),
        .INIT_RAM_0F(DSD_B7_0F)
    ) cb7 (
        .DO(csel7), .DI(32'd0), .BLKSELA(3'd0), .BLKSELB(3'd0),
        .ADA(14'd0), .ADB(ram_b),
        .CLKA(mclk), .CLKB(mclk), .CEA(1'b0), .CEB(1'b1),
        .OCE(1'b1), .RESET(1'b0)
    );

    // ---------------- FIR: 8 add/sub taps per MCLK per channel ----------------
    // The RAM outputs registered this cycle hold the coefficients for the
    // taps tap_base..tap_base+7, matching the 1-cycle read latency.
    //
    // Two pipeline stages with a register in between. The register is what
    // actually breaks the long combinational path: Gowin synthesis rebuilds
    // a sequential adder chain from ANY parenthesized 8-term sum, so a
    // balanced tree alone changes nothing (measured: identical 22.9 ns
    // worst path before and after re-parenthesizing). Stage 1 registers the
    // 8 muxed tap terms; stage 2 accumulates the previous group through a
    // 3-level adder tree. Bit-identical result: 8 x 32-bit terms fit in
    // 44 bits with no intermediate truncation.
    reg signed [43:0] t_l0, t_l1, t_l2, t_l3, t_l4, t_l5, t_l6, t_l7;
    reg signed [43:0] t_r0, t_r1, t_r2, t_r3, t_r4, t_r5, t_r6, t_r7;
    reg signed [43:0] sum_l;
    reg signed [43:0] sum_r;
    reg signed [43:0] out_sum_l;
    reg signed [43:0] out_sum_r;
    reg        valid_int;

    wire signed [43:0] group_sum_l =
        ((t_l0 + t_l1) + (t_l2 + t_l3)) + ((t_l4 + t_l5) + (t_l6 + t_l7));
    wire signed [43:0] group_sum_r =
        ((t_r0 + t_r1) + (t_r2 + t_r3)) + ((t_r4 + t_r5) + (t_r6 + t_r7));

    always @(posedge mclk or negedge rst_n) begin
        if (!rst_n) begin
            tapk <= 7'd0;
            tap_base <= 10'd0;
            fir_sr_l <= {TAPS{1'b0}};
            fir_sr_r <= {TAPS{1'b0}};
            t_l0 <= 44'sd0; t_l1 <= 44'sd0; t_l2 <= 44'sd0; t_l3 <= 44'sd0;
            t_l4 <= 44'sd0; t_l5 <= 44'sd0; t_l6 <= 44'sd0; t_l7 <= 44'sd0;
            t_r0 <= 44'sd0; t_r1 <= 44'sd0; t_r2 <= 44'sd0; t_r3 <= 44'sd0;
            t_r4 <= 44'sd0; t_r5 <= 44'sd0; t_r6 <= 44'sd0; t_r7 <= 44'sd0;
            sum_l <= 44'sd0;
            sum_r <= 44'sd0;
            out_sum_l <= 44'sd0;
            out_sum_r <= 44'sd0;
            valid_int <= 1'b0;
        end else begin
            tap_base <= {tapk, 3'd0};

            // Stage 1: mux the 8 terms of the current group into registers.
            t_l0 <= fir_sr_l[tap_base + 3'd0] ? $signed(csel0) : -$signed(csel0);
            t_l1 <= fir_sr_l[tap_base + 3'd1] ? $signed(csel1) : -$signed(csel1);
            t_l2 <= fir_sr_l[tap_base + 3'd2] ? $signed(csel2) : -$signed(csel2);
            t_l3 <= fir_sr_l[tap_base + 3'd3] ? $signed(csel3) : -$signed(csel3);
            t_l4 <= fir_sr_l[tap_base + 3'd4] ? $signed(csel4) : -$signed(csel4);
            t_l5 <= fir_sr_l[tap_base + 3'd5] ? $signed(csel5) : -$signed(csel5);
            t_l6 <= fir_sr_l[tap_base + 3'd6] ? $signed(csel6) : -$signed(csel6);
            t_l7 <= fir_sr_l[tap_base + 3'd7] ? $signed(csel7) : -$signed(csel7);
            t_r0 <= fir_sr_r[tap_base + 3'd0] ? $signed(csel0) : -$signed(csel0);
            t_r1 <= fir_sr_r[tap_base + 3'd1] ? $signed(csel1) : -$signed(csel1);
            t_r2 <= fir_sr_r[tap_base + 3'd2] ? $signed(csel2) : -$signed(csel2);
            t_r3 <= fir_sr_r[tap_base + 3'd3] ? $signed(csel3) : -$signed(csel3);
            t_r4 <= fir_sr_r[tap_base + 3'd4] ? $signed(csel4) : -$signed(csel4);
            t_r5 <= fir_sr_r[tap_base + 3'd5] ? $signed(csel5) : -$signed(csel5);
            t_r6 <= fir_sr_r[tap_base + 3'd6] ? $signed(csel6) : -$signed(csel6);
            t_r7 <= fir_sr_r[tap_base + 3'd7] ? $signed(csel7) : -$signed(csel7);

            // Stage 2: accumulate the previous group's registered terms.
            // tapk lag: the mux processes group tapk-1 and the sum
            // processes group tapk-2, so the lap boundary sits at tapk 1/2.
            if (tapk == 7'd0) begin
                // Sum adds group 126; snapshot the live delay line for the
                // next lap. Group 127 of THIS lap is still muxed from the
                // old snapshot in this same cycle (nonblocking order).
                sum_l <= sum_l + group_sum_l;
                sum_r <= sum_r + group_sum_r;
                fir_sr_l <= sr_l;
                fir_sr_r <= sr_r;
            end else if (tapk == 7'd1) begin
                // Group 127 completes the 1024-tap sum.
                sum_l <= sum_l + group_sum_l;
                sum_r <= sum_r + group_sum_r;
            end else if (tapk == 7'd2) begin
                // Capture the completed lap, restart with group 0.
                out_sum_l <= sum_l;
                out_sum_r <= sum_r;
                sum_l <= group_sum_l;
                sum_r <= group_sum_r;
            end else begin
                sum_l <= sum_l + group_sum_l;
                sum_r <= sum_r + group_sum_r;
            end

            valid_int <= (tapk == 7'd2) && decide_done;

            if (tapk == 7'd127)
                tapk <= 7'd0;
            else
                tapk <= tapk + 7'd1;
        end
    end

    // ---------------- output latch with saturation ----------------
    always @(posedge mclk or negedge rst_n) begin
        if (!rst_n) begin
            sample_valid <= 1'b0;
            sample_l <= 32'sd0;
            sample_r <= 32'sd0;
        end else begin
            sample_valid <= valid_int;
            if (out_sum_l > 44'sd2147483647)
                sample_l <= 32'sh7fffffff;
            else if (out_sum_l < -44'sd2147483648)
                sample_l <= 32'sh80000000;
            else
                sample_l <= out_sum_l[31:0];
            if (out_sum_r > 44'sd2147483647)
                sample_r <= 32'sh7fffffff;
            else if (out_sum_r < -44'sd2147483648)
                sample_r <= 32'sh80000000;
            else
                sample_r <= out_sum_r[31:0];
        end
    end

endmodule
