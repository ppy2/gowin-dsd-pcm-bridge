// DSD (native, DSD64..DSD512) to PCM 352.8/384 kHz converter.
//
// The transport presents: the bit clock on the BCLK pin, DATA1 (left) on
// the SDATA pin, and DATA2 (right) either on the LRCLK pin (Amanero-style,
// the classic behavior) or on a dedicated pin (dsd_data2_alt). When DSD_ON
// rises, a ~1 ms acquisition window counts the transitions of the
// dedicated pin sampled only at DSD bit-clock boundaries: if the line
// carries a bit-correlated stream (>= 16 bit-boundary transitions) it is
// used as DATA2, otherwise the LRCLK pin is used. Activity between bit
// boundaries (crosstalk, glitches) is ignored. The decision is latched for
// the whole DSD session and re-armed only while DSD_ON is low.
//
// The bit-clock period (2/4/8/16 MCLK) is averaged over the first 256
// bits and selects the decimation (64/32/16/8 bits per output sample).
// The decimator is a 1024-tap windowed-sinc FIR at the output rate
// (352.8/384 kHz): passband flat to ~20 kHz, <= -40 dB by 22.05 kHz so
// the DSD64 modulator noise folding into the audio band stays below the
// 16-bit floor. The input is 1-bit, so each tap is just an add/subtract
// of its coefficient (no multipliers); 8 taps are processed per MCLK per
// channel, one output pair per 128 MCLK. Coefficients live in 8 SDPB
