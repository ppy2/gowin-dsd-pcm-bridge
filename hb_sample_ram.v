// Delay-line RAM implemented with the Gowin GW5A BSRAM SDPB primitive
// (16-Kbit block SRAM, 512 words x 32 bits). Synchronous read: the address
// presented in cycle N is returned as read_data in cycle N+1.
//
// NOTE: the Tang Primer 25K carries GW5A-25A silicon (device version A),
// which has no shadow SSRAM slices. Distributed RAM primitives
// (RAM16S4/RAM16SDP4) cannot be placed on this device, so the delay lines
// deliberately use BSRAM instead.
