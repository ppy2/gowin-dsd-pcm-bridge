    input  wire [ADDR_BITS-1:0] read_addr,
    input  wire [31:0]          write_data,
    output wire [31:0]          read_data
);
    wire [8:0] wa = {{(9-ADDR_BITS){1'b0}}, write_addr};
    wire [8:0] ra = {{(9-ADDR_BITS){1'b0}}, read_addr};

