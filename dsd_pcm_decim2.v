            write_ptr  <= 7'd0;
            mac_base   <= 7'd0;
            pair_phase <= 1'b0;
            mac_cnt    <= 9'd0;
            c_cur      <= 32'sd0;
            acc_l      <= 66'sd0;
            acc_r      <= 66'sd0;
            out_valid  <= 1'b0;
            out_l      <= 32'sd0;
            out_r      <= 32'sd0;
