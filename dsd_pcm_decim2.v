                        out_l <= 32'sh7fffffff;
                    else if ($signed(acc_l[65:31]) < -35'sd2147483648)
                        out_l <= 32'sh80000000;
                    else
                        out_l <= acc_l[62:31];
                    if ($signed(acc_r[65:31]) > 35'sd2147483647)
                        out_r <= 32'sh7fffffff;
                    else if ($signed(acc_r[65:31]) < -35'sd2147483648)
                        out_r <= 32'sh80000000;
                    else
                        out_r <= acc_r[62:31];
                    out_valid <= 1'b1;
                end else begin
                    // Coefficient for the tap presented this cycle (its
                    // product lands in acc next cycle). mac_cnt <= 128,
                    // so 128 - mac_cnt fits the 7-bit tap index.
                    if ((mac_cnt >= 9'd1) && (mac_cnt <= 9'd128))
                        c_cur <= DSD_DECIM2_TAP(9'd128 - mac_cnt);
                    // Product add: c_cur registered last cycle x the data
                    // for the address presented last cycle.
                    if ((mac_cnt >= 9'd2) && (mac_cnt <= 9'd129)) begin
                        acc_l <= acc_l + {{2{prod_l[63]}}, prod_l};
                        acc_r <= acc_r + {{2{prod_r[63]}}, prod_r};
                    end
                    mac_cnt <= mac_cnt + 1'b1;
                end
            end
        end
    end

