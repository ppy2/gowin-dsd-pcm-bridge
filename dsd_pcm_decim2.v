                mac_base <= write_ptr;          // slot of this sample
                if (write_ptr == 7'd127)
                    write_ptr <= 7'd0;
                else
                    write_ptr <= write_ptr + 1'b1;

                if (!pair_phase && (mac_cnt == 9'd0)) begin
                    pair_phase <= 1'b1;
                    mac_cnt    <= 9'd1;
                    acc_l      <= 66'sd0;
                    acc_r      <= 66'sd0;
                end else if (pair_phase) begin
                    pair_phase <= 1'b0;
                end
            end

            // ---------------- MAC sweep (independent of in_valid) ----
