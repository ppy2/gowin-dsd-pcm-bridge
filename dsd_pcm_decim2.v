// PCM-domain x2 decimation anti-alias for the native DSD path.
//
// dsd_to_pcm.v outputs 352.8 kHz pairs on a 128-MCLK grid. This stage
// decimates by 2 to the frozen 176.4 kHz (MCLK/256) output grid so the
// result feeds the same dither/I2S/TDA1541 chain as the NOS regime.
//
// Filter: 128-tap Kaiser (beta=12), Q31, DC sum = 2^31 (unity gain on
// the dsd_to_pcm output scale). Response (tools/gen_dsd_decim2_coeffs.py
// --check): flat to 20.5 kHz (0.003 dB ripple), -102 dB by 40 kHz,
// -145 dB at the 156.4 kHz fold band - the first-stage DSD-noise residue
// above the audio and the /2 aliases stay below the 16-bit floor for
// every DSD rate (64..512).
//
// MAC schedule (one tap per MCLK, address presented combinationally):
// ring slots are 7-bit; slot (q+k) holds x[2n-(128-k)], so slot (q+1) is
// x[2n-127] and slot q is x[2n]. After an EVEN input at posedge T:
//   T:     ring write x[2n] at q; base <= q; mac_cnt <= 1; acc <= 0
//   T+m:   read_addr = base + m   (m = 1..128, 7-bit wrap: q+1 .. q)
//          c_cur <= tap(128-m)    (tap 127 at m=1 .. tap 0 at m=128)
//          the SDPB registers mem[read_addr] at this posedge
//   T+m+1: acc += c_cur * hist    (hist = mem[read_addr of T+m]; the
//          pairing: tap(129-m) x x[2n-(129-m)] for m = 1..128)
// The odd input (T+128, same posedge as m=128) writes the slot q+1,
// which is read only at m=1, so the convolution is never disturbed.
// The result is latched at T+130 (acc complete after the m=128 product
// entered at the end of T+129). One output pair per 256 MCLK.
